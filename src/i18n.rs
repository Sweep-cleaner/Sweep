/// Yer tutuculu çeviri (motor dizgileri için): anahtar İngilizce yazılır,
// Türkçe sözlükte karşılığı varsa o döner, yoksa anahtarın kendisi
// (yani İngilizce) kullanılır. Diğer diller otomatik İngilizce'ye düşer.
pub fn et(lang: &Lang, key: &str, args: &[impl AsRef<str>]) -> String {
    let mut s = t(lang, key);
    for arg in args {
        s = s.replacen("{}", arg.as_ref(), 1);
    }
    s
}


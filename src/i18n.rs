/// Çevir: eksik anahtar İngilizce'ye, o da yoksa anahtarına düşer.
pub fn t(lang: &Lang, key: &str) -> String {
    if let Some(hit) = dict(lang.code()).get(key) {
        return hit.to_string();
    }
    // Disk-dışı sistem zekası ekranlarının anahtarları ayrı tutulur: bu blok
    // 8 dilde de dolu olduğu için `all_languages_cover_english_keys` testinin
    // saydığı temel sözlük boyutunu değiştirmez.
    if let Some((_, hit)) = diskless_keys(lang.code()).iter().find(|(k, _)| *k == key) {
        return (*hit).to_string();
    }
    if let Some(hit) = dict("en").get(key) {
        return hit.to_string();
    }
    key.to_string()
}

/// Disk-dışı sistem zekası dizgileri (bellek, başlangıç, sistem sağlığı,
/// ağ, gizlilik) — 8 dilin tamamında karşılanır.
///
/// Her dil aynı anahtar kümesini taşır; eksik çeviri olursa
/// `diskless_covers_all_languages` testi yakalar.
pub fn diskless_keys(code: &str) -> &'static [(&'static str, &'static str)] {
    match code {
        "tr" => &DISKLESS_TR,
        "es" => &DISKLESS_ES,
        "ru" => &DISKLESS_RU,
        "fr" => &DISKLESS_FR,
        "de" => &DISKLESS_DE,
        "pt" => &DISKLESS_PT,
        "it" => &DISKLESS_IT,
        _ => &DISKLESS_EN,
    }
}


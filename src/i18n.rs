//! Çoklu dil altyapısı: `en` + `tr` sözlükleri, anahtar tabanlı çeviri.
//!
//! Dil sırası: `config.toml` → `languages[0]`; yoksa `LANG`/`LC_ALL`
//! ortam değişkeni; ikisi de yoksa İngilizce. Yeni dil eklemek = yeni
//! `match` kolu + `SUPPORTED` girdisi; eksik anahtar İngilizce'ye düşer.
//!
//! Kullanım: `t(&lang, "confirm_clean")`. GUI dizgileri Faz 3'te taşınacak;
//! CLI onay/rapor dizgileri şimdiden çevrili.

use std::collections::HashMap;
use std::sync::OnceLock;

/// Desteklenen diller (kod, görünen ad).
pub const SUPPORTED: &[(&str, &str)] = &[
    ("en", "English"),
    ("tr", "Türkçe"),
    ("es", "Español"),
    ("ru", "Русский"),
    ("fr", "Français"),
    ("de", "Deutsch"),
    ("pt", "Português"),
    ("it", "Italiano"),
];

/// Aktif dil.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Lang {
    code: String,
}

impl Lang {
    pub fn new(code: &str) -> Self {
        let code = code.trim().to_lowercase();
        let short = code.split(['.', '@', '_']).next().unwrap_or("en");
        let supported = SUPPORTED.iter().any(|(c, _)| *c == short);
        Self {
            code: if supported { short.into() } else { "en".into() },
        }
    }

    /// config → ortam → en.
    pub fn detect(languages: &[String]) -> Self {
        if let Some(first) = languages.first() {
            let lang = Self::new(first);
            if lang.code != "en" || first.starts_with("en") {
                return lang;
            }
        }
        for var in ["LANG", "LC_ALL", "LANGUAGE"] {
            if let Ok(value) = std::env::var(var) {
                let lang = Self::new(&value);
                if lang.code != "en" {
                    return lang;
                }
            }
        }
        Self::new("en")
    }

    pub fn code(&self) -> &str {
        &self.code
    }
}

